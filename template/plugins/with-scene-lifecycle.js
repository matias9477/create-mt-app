/**
 * Adopts the UIKit scene-based life cycle on Expo SDK 57.
 *
 * Apps built with the iOS 27 SDK (Xcode 27) fail to launch without it:
 * "UIScene life cycle is required for apps built with this SDK". SDK 58's
 * template ships this natively (ExpoAppSceneDelegate); SDK 57 doesn't, so this
 * ports it. Remove this plugin when upgrading to SDK 58.
 *
 * - Info.plist: declares a single-scene manifest pointing at SceneDelegate.
 * - SceneDelegate.swift: creates the window from the scene, starts React
 *   Native into it, and forwards life-cycle / URL / user-activity events to
 *   the ExpoAppDelegate (which fans them out to Expo's subscribers).
 * - AppDelegate.swift: stops creating its own window; the scene does it.
 */
const fs = require("fs");
const path = require("path");
const {
  IOSConfig,
  withAppDelegate,
  withDangerousMod,
  withInfoPlist,
  withXcodeProject,
} = require("expo/config-plugins");

const SCENE_DELEGATE = `internal import Expo
import React
import UIKit

// Generated by plugins/with-scene-lifecycle.js — edit there, not here.
@objc(SceneDelegate)
class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  private var appDelegate: AppDelegate? {
    UIApplication.shared.delegate as? AppDelegate
  }

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard let windowScene = scene as? UIWindowScene,
      let appDelegate,
      let factory = appDelegate.reactNativeFactory
    else { return }

    let window = UIWindow(windowScene: windowScene)
    self.window = window
    // Code that reads UIApplication.shared.delegate?.window keeps working.
    appDelegate.window = window

    // Linking.getInitialURL() only reads launch options, but under scenes a
    // cold-start link arrives in connectionOptions, so rebuild them.
    var launchOptions: [UIApplication.LaunchOptionsKey: Any] = [:]
    if let url = connectionOptions.urlContexts.first?.url {
      launchOptions[UIApplication.LaunchOptionsKey(rawValue: "UIApplicationLaunchOptionsURLKey")] = url
    }
    if let activity = connectionOptions.userActivities.first(where: {
      $0.activityType == NSUserActivityTypeBrowsingWeb
    }) {
      launchOptions[UIApplication.LaunchOptionsKey(rawValue: "UIApplicationLaunchOptionsUserActivityDictionaryKey")] = [
        "UIApplicationLaunchOptionsUserActivityTypeKey": activity.activityType,
        "UIApplicationLaunchOptionsUserActivityKey": activity,
      ]
    }

    factory.startReactNative(
      withModuleName: "main",
      in: window,
      launchOptions: launchOptions.isEmpty ? nil : launchOptions)
  }

  func sceneDidDisconnect(_ scene: UIScene) {
    window = nil
  }

  // UIKit stops calling the app-delegate life-cycle methods under scenes;
  // forward them so Expo's subscribers still hear about them.
  func sceneDidBecomeActive(_ scene: UIScene) {
    appDelegate?.applicationDidBecomeActive(UIApplication.shared)
  }

  func sceneWillResignActive(_ scene: UIScene) {
    appDelegate?.applicationWillResignActive(UIApplication.shared)
  }

  func sceneWillEnterForeground(_ scene: UIScene) {
    appDelegate?.applicationWillEnterForeground(UIApplication.shared)
  }

  func sceneDidEnterBackground(_ scene: UIScene) {
    appDelegate?.applicationDidEnterBackground(UIApplication.shared)
  }

  // Warm deep links (custom scheme, widget taps).
  func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
    for context in URLContexts {
      var options: [UIApplication.OpenURLOptionsKey: Any] = [
        .openInPlace: context.options.openInPlace
      ]
      if let source = context.options.sourceApplication {
        options[.sourceApplication] = source
      }
      if let annotation = context.options.annotation {
        options[.annotation] = annotation
      }
      _ = appDelegate?.application(UIApplication.shared, open: context.url, options: options)
    }
  }

  func scene(_ scene: UIScene, continue userActivity: NSUserActivity) {
    _ = appDelegate?.application(
      UIApplication.shared, continue: userActivity, restorationHandler: { _ in })
  }
}
`;

const START_RN_IN_APP_DELEGATE =
  /\n#if os\(iOS\) \|\| os\(tvOS\)\n\s*window = UIWindow\(frame: UIScreen\.main\.bounds\)\n\s*factory\.startReactNative\([\s\S]*?\)\n#endif\n/;

const withSceneManifest = (config) =>
  withInfoPlist(config, (cfg) => {
    cfg.modResults.UIApplicationSceneManifest = {
      UIApplicationSupportsMultipleScenes: false,
      UISceneConfigurations: {
        UIWindowSceneSessionRoleApplication: [
          {
            UISceneConfigurationName: "Default Configuration",
            UISceneDelegateClassName: "$(PRODUCT_MODULE_NAME).SceneDelegate",
          },
        ],
      },
    };
    return cfg;
  });

const withAppDelegateWithoutWindow = (config) =>
  withAppDelegate(config, (cfg) => {
    const { contents } = cfg.modResults;
    if (contents.includes("started by SceneDelegate")) return cfg;
    if (!START_RN_IN_APP_DELEGATE.test(contents)) {
      throw new Error(
        "[with-scene-lifecycle] AppDelegate.swift no longer matches the SDK 57 template; update the plugin.",
      );
    }
    cfg.modResults.contents = contents.replace(
      START_RN_IN_APP_DELEGATE,
      "\n    // The window is created and React Native is started by SceneDelegate\n" +
        "    // (scene life cycle, required by the iOS 27 SDK).\n",
    );
    return cfg;
  });

const withSceneDelegateFile = (config) =>
  withDangerousMod(config, [
    "ios",
    (cfg) => {
      const projectName = IOSConfig.XcodeUtils.getProjectName(cfg.modRequest.projectRoot);
      const file = path.join(
        cfg.modRequest.platformProjectRoot,
        projectName,
        "SceneDelegate.swift",
      );
      fs.writeFileSync(file, SCENE_DELEGATE);
      return cfg;
    },
  ]);

const withSceneDelegateInProject = (config) =>
  withXcodeProject(config, (cfg) => {
    const project = cfg.modResults;
    const projectName = IOSConfig.XcodeUtils.getProjectName(cfg.modRequest.projectRoot);
    const filepath = `${projectName}/SceneDelegate.swift`;
    if (!project.hasFile(filepath)) {
      const target = IOSConfig.XcodeUtils.getApplicationNativeTarget({ project, projectName });
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({
        filepath,
        groupName: projectName,
        project,
        targetUuid: target.uuid,
      });
    }
    return cfg;
  });

module.exports = (config) =>
  withSceneDelegateInProject(
    withSceneDelegateFile(withAppDelegateWithoutWindow(withSceneManifest(config))),
  );
